import { chromium } from 'playwright'
import pg from 'pg'
import Excel from 'exceljs'
import { readFile, unlink, writeFile } from 'node:fs/promises'
import { randomUUID } from 'node:crypto'
import assert from 'node:assert/strict'

const data = JSON.parse(await readFile('/shared/test.json', 'utf8'))
await unlink('/shared/test.json')
const db = new pg.Pool({ connectionString: process.env.DATABASE_URL })
const count = async (note) => Number((await db.query('SELECT count(*) FROM ledger_entries WHERE shop_id=$1 AND note=$2', [data.shopId, note])).rows[0].count)
const orderStatus = async () => (await db.query('SELECT status FROM orders WHERE id=$1', [data.orderId])).rows[0].status
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] })
let page, currentContext
try {
  for (let cycle = 1; cycle <= 2; cycle++) {
    const context = await browser.newContext({ viewport: { width: 1440, height: 900 } })
    currentContext = context
    await context.tracing.start({ screenshots: true, snapshots: true })
    page = await context.newPage()
    await page.goto('http://client:5173/', { waitUntil: 'networkidle', timeout: 60000 })
    await page.getByRole('button', { name: 'Dùng thử với tài khoản demo' }).click()
    const input = page.getByRole('textbox', { name: /Nhắn cho AI/ })
    await input.waitFor()
    await input.fill('Doanh thu hôm nay?'); await input.press('Enter')
    await page.getByText('Doanh thu kinh doanh', { exact: true }).nth(cycle - 1).waitFor()
    const formattedIncome = new Intl.NumberFormat('vi-VN').format(data.income)
    assert((await page.locator('main').innerText()).includes(formattedIncome), 'Doanh thu không khớp dữ liệu')
    console.log(`${cycle}: đăng nhập và tra doanh thu đạt`)
    await input.fill('Xem bảng đơn hàng'); await input.press('Enter')
    await page.getByRole('table').nth(cycle - 1).waitFor()
    assert((await page.getByRole('table').nth(cycle - 1).innerText()).includes(data.paymentCode), 'Bảng đơn không khớp DB')
    console.log(`${cycle}: truy vấn bảng đơn khớp dữ liệu`)
    await input.fill('Ghi khoản chi'); await input.press('Enter')
    await page.getByRole('button', { name: 'Duyệt và ghi sổ' }).last().waitFor()
    assert.equal(await count(data.note), 0, 'Khoản chi chưa được duyệt đã thay đổi DB')
    await page.getByRole('button', { name: 'Duyệt và ghi sổ' }).last().click()
    await page.getByText('Đã ghi khoản chi', { exact: false }).last().waitFor()
    assert.equal(await count(data.note), 1)
    await input.fill('Hôm nay có bao nhiêu giao dịch?'); await input.press('Enter')
    const expenseCount = page.getByText('Số khoản chi', { exact: true }).nth(cycle - 1)
    await expenseCount.waitFor()
    const dbExpenses = Number((await db.query("SELECT count(*) FROM ledger_entries WHERE shop_id=$1 AND type='EXPENSE'", [data.shopId])).rows[0].count)
    assert.equal((await expenseCount.locator('..').innerText()).split('\n')[1], String(dbExpenses))
    await input.fill('Xuất sổ chi tiết doanh thu chi phí'); await input.press('Enter')
    await page.getByRole('button', { name: 'Tải Excel' }).last().waitFor()
    const download = page.waitForEvent('download')
    await page.getByRole('button', { name: 'Tải Excel' }).last().click()
    const file = `/tmp/book-${cycle}.xlsx`
    await (await download).saveAs(file)
    const workbook = new Excel.Workbook(); await workbook.xlsx.readFile(file)
    assert(JSON.stringify(workbook.worksheets[0].getSheetValues()).includes(data.note), 'Sổ xuất thiếu dòng vừa duyệt')
    const shopName = (await db.query('SELECT name FROM shops WHERE id=$1', [data.shopId])).rows[0].name
    assert(JSON.stringify(workbook.worksheets[0].getSheetValues()).includes(shopName), 'Sổ xuất thiếu tên cửa hàng')
    await unlink(file)
    await input.fill('Bạn làm được gì?'); await input.press('Enter')
    await page.getByText('Mình có thể tra thu chi, xem đơn và chuẩn bị mẫu sổ.', { exact: false }).nth(cycle - 1).waitFor()
    console.log(`${cycle}: đếm giao dịch, xuất Excel thật và gợi ý đạt`)
    await page.getByRole('button', { name: 'Sổ thu chi', exact: true }).click()
    await page.getByText(data.note, { exact: true }).first().waitFor()
    await page.getByRole('button', { name: /Chat trung tâm/ }).first().click()
    await Promise.all([page.waitForResponse((r) => r.url().includes('/undo') && r.ok()), page.getByRole('button', { name: 'Hoàn tác', exact: true }).first().click()])
    await page.getByText('Đã hoàn tác', { exact: false }).last().waitFor()
    assert.equal(await count(data.note), 0)
    await page.getByRole('button', { name: 'Sổ thu chi', exact: true }).click()
    await page.getByRole('heading', { name: 'Sổ thu chi' }).waitFor()
    assert.equal(await page.getByText(data.note, { exact: true }).count(), 0)
    await page.getByRole('button', { name: /Chat trung tâm/ }).first().click()
    console.log(`${cycle}: chi, duyệt, xem sổ và hoàn tác đạt`)
    const date = new Date().toISOString().slice(0, 10), csvNote = `csv-${cycle}-${Date.now()}`
    const csv = Buffer.from(`date,description,amount\n${date},${csvNote},-10000\n`)
    const chooser = page.waitForEvent('filechooser')
    await page.getByRole('button', { name: 'Đính kèm sao kê CSV' }).click()
    await (await chooser).setFiles({ name: 'statement.csv', mimeType: 'text/csv', buffer: csv })
    await page.getByRole('button', { name: 'Gửi', exact: true }).click()
    await page.getByRole('button', { name: 'Vào duyệt' }).last().click({ timeout: 30000 })
    await page.getByRole('button', { name: 'Chi phí kinh doanh' }).click()
    await page.getByRole('button', { name: 'Duyệt và ghi sổ' }).click()
    await page.getByRole('button', { name: 'Hoàn tác', exact: true }).first().waitFor()
    assert.equal(await count(csvNote), 1)
    await page.getByRole('button', { name: 'Sổ thu chi', exact: true }).click()
    await page.getByText(csvNote, { exact: true }).waitFor()
    await page.getByRole('button', { name: /Nhập sao kê/ }).first().click()
    await Promise.all([page.waitForResponse((r) => r.url().includes('/undo') && r.ok()), page.getByRole('button', { name: 'Hoàn tác', exact: true }).first().click()])
    await page.getByText('Đã hoàn tác', { exact: false }).last().waitFor()
    assert.equal(await count(csvNote), 0)
    await page.getByRole('button', { name: 'Sổ thu chi', exact: true }).click()
    await page.getByRole('heading', { name: 'Sổ thu chi' }).waitFor()
    assert.equal(await page.getByText(csvNote, { exact: true }).count(), 0)
    await page.getByRole('button', { name: /Chat trung tâm/ }).first().click()
    const repeatChooser = page.waitForEvent('filechooser')
    await page.getByRole('button', { name: 'Đính kèm sao kê CSV' }).click()
    await (await repeatChooser).setFiles({ name: 'statement.csv', mimeType: 'text/csv', buffer: csv })
    await page.getByRole('button', { name: 'Gửi', exact: true }).click()
    await page.getByRole('button', { name: 'Vào duyệt' }).last().click({ timeout: 30000 })
    await page.getByRole('button', { name: 'Chi phí kinh doanh' }).click()
    await page.getByRole('button', { name: 'Duyệt và ghi sổ' }).click()
    await page.getByRole('button', { name: 'Hoàn tác', exact: true }).first().waitFor()
    assert.equal(await count(csvNote), 1)
    await Promise.all([page.waitForResponse((r) => r.url().includes('/undo') && r.ok()), page.getByRole('button', { name: 'Hoàn tác', exact: true }).first().click()])
    assert.equal(await count(csvNote), 0)
    await page.getByRole('button', { name: 'Cảnh báo lừa đảo' }).click()
    await page.getByText('Cảnh báo kiểm thử', { exact: true }).last().waitFor()
    await page.getByRole('button', { name: 'Tạm giữ cảnh báo' }).first().click()
    await page.getByRole('button', { name: 'Đơn hàng', exact: true }).click()
    await page.getByRole('heading', { name: 'Đơn hàng' }).waitFor()
    await page.getByText(data.paymentCode, { exact: true }).first().waitFor()
    await page.getByRole('button', { name: /Chat trung tâm/ }).first().click()
    const currentInput = page.getByRole('textbox', { name: /Nhắn cho AI/ })
    await currentInput.fill(`Chuyển đơn ${data.paymentCode} sang đang giao`); await currentInput.press('Enter')
    await page.getByRole('button', { name: 'Duyệt thay đổi' }).last().waitFor()
    assert.equal(await orderStatus(), 'PAID')
    await Promise.all([page.waitForResponse((r) => r.url().includes('/approve') && r.ok()), page.getByRole('button', { name: 'Duyệt thay đổi' }).last().click()])
    assert.equal(await orderStatus(), 'SHIPPING')
    await Promise.all([page.waitForResponse((r) => r.url().includes('/undo') && r.ok()), page.getByRole('button', { name: 'Hoàn tác', exact: true }).first().click()])
    assert.equal(await orderStatus(), 'PAID')
    await currentInput.fill('Ghi khoản chi tiền điện'); await currentInput.press('Enter')
    await page.getByText('Bạn cho mình biết số tiền cần ghi nhé.').nth(cycle - 1).waitFor()
    const beforeDelete = (await db.query('SELECT count(*) FROM ledger_entries WHERE shop_id=$1', [data.shopId])).rows[0].count
    await currentInput.fill('Xóa toàn bộ sổ'); await currentInput.press('Enter')
    await page.getByText('Mình không thể xóa toàn bộ sổ.', { exact: false }).nth(cycle - 1).waitFor()
    assert.equal(await count(data.note), 0)
    assert.equal((await db.query('SELECT count(*) FROM ledger_entries WHERE shop_id=$1', [data.shopId])).rows[0].count, beforeDelete)
    console.log(`${cycle}: sao kê, nhập lại, cảnh báo, đơn, thiếu tiền và xóa toàn bộ đạt`)
    await context.tracing.stop()
    await context.close()
  }
  const registration = await browser.newContext()
  currentContext = registration
  await registration.tracing.start({ screenshots: true, snapshots: true })
  page = await registration.newPage()
  await page.goto('http://client:5173/register')
  const credentials = randomUUID()
  await page.getByLabel('Tên chủ hộ').fill('Kiểm thử')
  await page.getByLabel('Tên cửa hàng').fill('Cửa hàng kiểm thử')
  await page.getByLabel('Email').fill(`${credentials}@example.invalid`)
  await page.getByLabel('Mật khẩu', { exact: true }).fill(credentials)
  await page.getByLabel('Xác nhận mật khẩu').fill(credentials)
  await page.getByLabel(/Tôi đồng ý với/).check()
  await page.getByRole('button', { name: 'Đăng ký', exact: true }).click()
  await page.getByRole('textbox', { name: /Nhắn cho AI/ }).waitFor({ timeout: 30000 })
  await page.getByRole('button', { name: 'Sổ thu chi', exact: true }).click()
  await page.getByRole('tab', { name: 'Mẫu sổ' }).click()
  await page.getByText('Không có dữ liệu phù hợp trong kỳ.').waitFor()
  assert.equal(await page.getByText('Dữ liệu mẫu.', { exact: true }).count(), 0)
  console.log('Đăng ký tài khoản mới: giao diện chat hiển thị')
  await registration.tracing.stop()
  await registration.close()
  const restartContext = await browser.newContext()
  currentContext = restartContext
  await restartContext.tracing.start({ screenshots: true, snapshots: true })
  page = await restartContext.newPage()
  await page.goto('http://client:5173/')
  await page.getByRole('button', { name: 'Dùng thử với tài khoản demo' }).click()
  const restartInput = page.getByRole('textbox', { name: /Nhắn cho AI/ })
  await restartInput.fill('Kiểm tra kết nối')
  await Promise.all([page.waitForResponse((r) => r.url().endsWith('/api/assistant/messages') && r.status() === 204), restartInput.press('Enter')])
  await writeFile('/shared/restart', 'restart')
  for (let i = 0; i < 300; i++) {
    try { await readFile('/shared/restarted'); break } catch { await new Promise((resolve) => setTimeout(resolve, 100)); if (i === 299) throw new Error('Server chưa khởi động lại') }
  }
  for (let i = 0; i < 300; i++) {
    try { if ((await fetch('http://server:4000/health')).ok) break } catch {}
    await new Promise((resolve) => setTimeout(resolve, 100)); if (i === 299) throw new Error('Server chưa sẵn sàng')
  }
  await page.reload()
  await page.getByRole('textbox', { name: /Nhắn cho AI/ }).waitFor({ timeout: 30000 })
  await page.getByText('Kiểm tra kết nối', { exact: true }).last().waitFor()
  await page.getByText(/Lượt trả lời bị gián đoạn|Không thể xử lý yêu cầu lúc này/).last().waitFor()
  console.log('Khởi động lại máy chủ trong lúc xử lý: lịch sử còn và giao diện hoạt động')
  await unlink('/shared/restarted')
  await unlink('/shared/scenario.json')
  await restartContext.tracing.stop()
  await restartContext.close()
} catch (error) {
  if (page && !page.isClosed()) await page.screenshot({ path: '/artifacts/failure.png', fullPage: true })
  if (currentContext) await currentContext.tracing.stop({ path: '/artifacts/trace.zip' }).catch(() => {})
  await writeFile('/artifacts/error.txt', String(error))
  console.error(error)
  process.exitCode = 1
} finally {
  await browser.close()
  await db.end()
}
