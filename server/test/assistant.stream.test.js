import { test } from 'node:test'
import assert from 'node:assert/strict'
import { randomUUID } from 'node:crypto'
import jwt from 'jsonwebtoken'

test('assistant SSE isolates shops and persists messages', { skip: !process.env.TEST_DATABASE_URL, timeout: 15000 }, async () => {
  process.env.DATABASE_URL = process.env.TEST_DATABASE_URL
  const { pool } = await import('../src/db/pool.js')
  const { env } = await import('../src/config/env.js')
  const { createApp } = await import('../src/app.js')
  const { recover } = await import('../src/services/assistant/assistant.service.js')
  const { acquire, release, closeAllStreams } = await import('../src/services/assistant/events.js')
  const server = createApp().listen(0, '127.0.0.1')
  await new Promise((resolve) => server.once('listening', resolve))
  const base = `http://127.0.0.1:${server.address().port}`
  const shopA = randomUUID(), shopB = randomUUID(), userA = randomUUID(), userB = randomUUID()
  const token = (shopId, userId) => jwt.sign({ shopId }, env.JWT_SECRET, { subject: userId, algorithm: 'HS256' })
  const headers = (value) => ({ Authorization: `Bearer ${value}`, 'Content-Type': 'application/json' })
  const abortA = new AbortController(), abortB = new AbortController()
  let readerA, readerB
  try {
    await pool.query('INSERT INTO shops (id, name) VALUES ($1, $2), ($3, $4)', [shopA, 'Shop A', shopB, 'Shop B'])
    await pool.query("INSERT INTO assistant_messages (shop_id,id,conversation_id,role,body) VALUES ($1,'lost-turn','lost-thread','user',$2)", [shopB, { id: 'lost-turn', role: 'user', text: 'Câu bị gián đoạn' }])
    await pool.query("INSERT INTO assistant_threads (shop_id,id,title,status,scope) VALUES ($1,'interrupted','Test','running','Test')", [shopA])
    const stepId = randomUUID()
    const interrupted = { id: 'interrupted-message', role: 'assistant', blocks: [{ type: 'agentStep', stepId, state: 'working' }] }
    await pool.query('INSERT INTO assistant_messages (shop_id,id,conversation_id,role,body) VALUES ($1,$2,$3,$4,$5)', [shopA, interrupted.id, 'interrupted', 'assistant', interrupted])
    await pool.query("INSERT INTO assistant_steps (id,shop_id,conversation_id,message_id,state,view,actions) VALUES ($1,$2,'interrupted',$3,'working',$4,'[]')", [stepId, shopA, interrupted.id, interrupted.blocks[0]])
    await recover()
    await recover()
    const recovered = await pool.query("SELECT body FROM assistant_messages WHERE shop_id=$1 AND conversation_id='lost-thread' ORDER BY seq", [shopB])
    assert.equal(recovered.rowCount, 2)
    assert.match(recovered.rows[1].body.blocks[0].text, /bị gián đoạn/)
    assert.equal((await pool.query('SELECT state FROM assistant_steps WHERE id = $1', [stepId])).rows[0].state, 'failed')
    assert.equal((await pool.query("SELECT status FROM assistant_threads WHERE shop_id = $1 AND id = 'interrupted'", [shopA])).rows[0].status, 'done')
    assert.equal((await pool.query('SELECT body FROM assistant_messages WHERE shop_id = $1 AND id = $2', [shopA, interrupted.id])).rows[0].body.blocks[0].state, 'failed')
    assert.equal(acquire(shopA, 'hub'), true)
    const busy = await fetch(`${base}/api/assistant/messages`, { method: 'POST', headers: headers(token(shopA, userA)), body: JSON.stringify({ conversationId: 'hub', text: 'x', attachments: [] }) })
    assert.equal(busy.status, 409)
    assert.equal((await busy.json()).error.code, 'ASSISTANT_BUSY')
    release(shopA, 'hub')
    const responseA = await fetch(`${base}/api/assistant/stream`, { headers: headers(token(shopA, userA)), signal: abortA.signal })
    const responseB = await fetch(`${base}/api/assistant/stream`, { headers: headers(token(shopB, userB)), signal: abortB.signal })
    assert.equal(responseA.status, 200)
    assert.match(responseA.headers.get('content-type'), /^text\/event-stream/)
    readerA = responseA.body.getReader(); readerB = responseB.body.getReader()
    const firstA = new TextDecoder().decode((await readerA.read()).value)
    const firstB = new TextDecoder().decode((await readerB.read()).value)
    assert.match(firstA, /^event: snapshot\n/)
    assert.match(firstB, /^event: snapshot\n/)
    assert.match(firstA, /Shop A/); assert.doesNotMatch(firstB, /Shop A/)
    const body = JSON.stringify({ conversationId: 'hub', text: 'Kiểm tra', attachments: [] })
    assert.equal((await fetch(`${base}/api/assistant/messages`, { method: 'POST', headers: headers(token(shopA, userA)), body })).status, 204)
    let events = ''
    while (!events.includes('"role":"assistant"')) events += new TextDecoder().decode((await readerA.read()).value)
    assert.match(events, /event: message/)
    assert.match(events, /Kiểm tra/)
    const rows = await pool.query("SELECT body FROM assistant_messages WHERE shop_id = $1 AND conversation_id = 'hub' ORDER BY seq", [shopA])
    assert.equal(rows.rowCount, 2)
    assert.equal(rows.rows[0].body.text, 'Kiểm tra')
    const pendingB = readerB.read()
    const other = await Promise.race([pendingB.then(() => 'received'), new Promise((resolve) => setTimeout(() => resolve('none'), 250))])
    assert.equal(other, 'none')
    const wrongThread = JSON.stringify({ conversationId: 'other-thread', text: 'x', attachments: [] })
    await pool.query("INSERT INTO assistant_threads (shop_id,id,title,status,scope) VALUES ($1,'other-thread','Test','done','Test')", [shopA])
    assert.equal((await fetch(`${base}/api/assistant/messages`, { method: 'POST', headers: headers(token(shopB, userB)), body: wrongThread })).status, 404)
    const reconnect = await fetch(`${base}/api/assistant/stream`, { headers: headers(token(shopA, userA)) })
    const reconnectReader = reconnect.body.getReader()
    assert.match(new TextDecoder().decode((await reconnectReader.read()).value), /Kiểm tra/)
    await reconnectReader.cancel()
    closeAllStreams()
    assert.equal((await pendingB).done, true)
  } finally {
    abortA.abort(); abortB.abort()
    await readerA?.cancel().catch(() => {}); await readerB?.cancel().catch(() => {})
    await new Promise((resolve) => server.close(resolve))
    await pool.end()
  }
})
